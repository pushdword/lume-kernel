uint8_t lume_font_column(unsigned c, unsigned x)
{
    if (x >= 5)
        return 0;
    if (c >= 'a' && c <= 'z')
        return lowercase[(unsigned)(c - 'a')][x];
    if (c >= 'A' && c <= 'Z')
        return glyphs[(unsigned)(c - 'A')][x];
    if (c >= '0' && c <= '9')
        return glyphs[26 + (unsigned)(c - '0')][x];
    if (c == '/')
        return (uint8_t)(64u >> x);
    if (c == '-')
        return 8;
    if (c == '_')
        return 64;
    if (c == '.')
        return x == 2 ? 64 : 0;
    if (c == ':')
        return x == 2 ? 36 : 0;
    if (c == '>')
    {
        static const uint8_t g[5] = {65, 34, 20, 8, 0};
        return g[x];
    }
    if (c == '<')
    {
        static const uint8_t g[5] = {0, 8, 20, 34, 65};
        return g[x];
    }
    if (c == '=')
        return 20;
    if (c == '!')
        return x == 2 ? 95 : 0;
    if (c == '?')
    {
        static const uint8_t q[5] = {2, 1, 81, 9, 6};
        return q[x];
    }
    if (c == '\\')
        return (uint8_t)(1u << x);
    if (c == '|')
        return x == 2 ? 127 : 0;
    if (c == '\'')
        return x == 2 ? 3 : 0;
    if (c == '"')
        return (x == 1 || x == 3) ? 3 : 0;
    if (c == '(')
        return x == 2 ? 62 : x == 3 ? 65 : 0;
    if (c == ')')
        return x == 2 ? 62 : x == 1 ? 65 : 0;
    if (c == '[')
        return x == 1 ? 127 : (x == 2 || x == 3) ? 65 : 0;
    if (c == ']')
        return x == 3 ? 127 : (x == 1 || x == 2) ? 65 : 0;
    if (c == ',')
        return x == 1 ? 64 : x == 2 ? 32 : 0;
    if (c == '+')
        return x == 2 ? 62 : 8;
    if (c == '*')
        return x == 2 ? 62 : (x == 1 || x == 3) ? 20 : 8;
    if (c == '#')
        return (x == 1 || x == 3) ? 127 : 20;

    static const struct
    {
        unsigned code;
        uint8_t columns[5];
    } punctuation[] = {
        {'$', {36, 42, 127, 42, 18}}, {'%', {35, 19, 8, 100, 98}}, {'&', {54, 73, 85, 34, 80}},
        {';', {0, 64, 38, 0, 0}},     {'@', {62, 65, 93, 85, 30}}, {'^', {4, 2, 1, 2, 4}},
        {'`', {0, 1, 2, 4, 0}},       {'{', {0, 8, 54, 65, 0}},    {'}', {0, 65, 54, 8, 0}},
        {'~', {8, 4, 8, 16, 8}},
    };

    for (unsigned i = 0; i < sizeof(punctuation) / sizeof(punctuation[0]); ++i)
        if (c == punctuation[i].code)
            return punctuation[i].columns[x];
    return 0;
}
